-- Отказы биржи по нативному трейлу (10.11.2026, продолжение разбора #825). Биржа может отклонить
-- уже принятый TRAILING_STOP_MARKET: id ордера выдан, а его сырой статус — FAILED. Такой id
-- оставался в executor_orders.trail_order_id: такт сверки считал трейл живым, почасовой фолбэк
-- позицию пропускал — она шла без трейла до выхода по рынку после такта журнала.
-- Теперь при живой позиции executor ставит трейл заново штатным путём: не больше трёх отказов
-- на сигнал, между отказом и новой постановкой не меньше 5 минут; после третьего отказа
-- нативный трейл по сигналу не ставится, позицию ведёт почасовой стоп за трейлом журнала
-- (bingx_executor._sync_trail_stops). Счёт и пауза живут в БД — переживают рестарт.
--
-- executor_orders.trail_fails — сколько раз биржа отклонила нативный трейл сигнала при живой
--   позиции (NULL — ни разу). 3 — нативный трейл по сигналу больше не ставится.
-- executor_orders.trail_failed_at — когда учтён последний отказ (UTC ISO-8601): от него
--   считается пауза. Сбрасывается в NULL, когда штатный путь захватывает новую постановку,
--   поэтому NOT NULL при стоящем id значит «отказ ЭТОГО трейла уже посчитан» — после
--   рестарта он не считается второй раз. После третьего отказа остаётся как есть.
-- Для уже ведущихся сигналов — NULL: отказы до миграции не считались.
ALTER TABLE executor_orders ADD COLUMN trail_fails INTEGER;
ALTER TABLE executor_orders ADD COLUMN trail_failed_at TEXT;
