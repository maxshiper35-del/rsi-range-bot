-- Фактическая цена выхода сделки.
-- До трейлинга выход всегда совпадал с одним из опубликованных уровней (stop / tp1..tp3),
-- поэтому колонка была не нужна: /stats восстанавливал цену по статусу. С подтягиваемым
-- стопом выход происходит по цене, которой в исходном сигнале нет, — её надо хранить,
-- иначе «ход цены» в статистике будет считаться по устаревшему уровню стопа.
-- NULL = старое поведение (цена берётся по статусу), история не переписывается.
ALTER TABLE signals ADD COLUMN exit_price REAL;
